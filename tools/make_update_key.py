#!/usr/bin/env python3
"""Owner one-time setup: generate the BeeSky update-signing keypair.

    python3 tools/make_update_key.py [--key-out update-signing-key.pem]
                                     [--module-out beesky/core/update_key.py]
                                     [--force]

What it does:

  * shells out to ``openssl`` (present on this VM, on dev machines
    and on the GitHub windows runners' Git Bash) to generate an
    RSA-2048 private key at --key-out,
  * extracts the modulus with ``openssl rsa -modulus`` and writes the
    PUBLIC half into --module-out (default
    ``beesky/core/update_key.py``) as ``UPDATE_RSA_N_HEX`` with
    ``UPDATE_RSA_E = 65537``,
  * prints the follow-up steps: the PRIVATE key file must be stored
    as the GitHub Actions secret ``UPDATE_SIGNING_KEY`` and then
    deleted/moved somewhere safe — it must NEVER be committed. The
    generated module file is the part you commit.

After this one-time setup every tagged release signs its own
``update-manifest.json`` in CI (docs/updating.md).
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_KEY_OUT = REPO_ROOT / "update-signing-key.pem"
DEFAULT_MODULE_OUT = REPO_ROOT / "beesky" / "core" / "update_key.py"
EXPONENT = 65537

MODULE_TEMPLATE = '''"""BeeSky update-channel public key (compile-time constant).

The values here are the PUBLIC half of the RSA-2048 keypair whose
private half signs ``update-manifest.json`` on every GitHub Release
(see docs/updating.md). Clients verify release manifests against this
modulus before trusting a single byte of them.

Generated by tools/make_update_key.py — do not edit by hand. The
private half lives ONLY as the GitHub Actions secret
``UPDATE_SIGNING_KEY``; it is not, and must never be, in this repo.
"""

# RSA modulus (hex, no 0x prefix) of the update-signing public key,
# or None while the channel is not configured.
UPDATE_RSA_N_HEX: str | None = {n_hex!r}

# RSA public exponent. Fixed by tools/make_update_key.py.
UPDATE_RSA_E = {e}
'''


def _run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(f"command failed: {' '.join(cmd)}\n"
                         f"{result.stderr.strip()}")
    return result.stdout


def generate(key_out: Path, module_out: Path, force: bool = False) -> str:
    """Generate the keypair; return the modulus hex string."""
    for path in (key_out, module_out):
        if path.exists() and not force:
            raise SystemExit(f"{path} already exists — pass --force to "
                             "overwrite (a new keypair invalidates "
                             "manifests signed with the old one)")
    key_out.parent.mkdir(parents=True, exist_ok=True)
    _run(["openssl", "genpkey", "-algorithm", "RSA",
          "-pkeyopt", f"rsa_keygen_bits:2048",
          "-pkeyopt", f"rsa_keygen_pubexp:{EXPONENT}",
          "-out", str(key_out)])
    try:
        key_out.chmod(0o600)
    except OSError:
        pass  # best effort (Windows ACLs differ); the file leaves anyway
    modulus_line = _run(["openssl", "rsa", "-in", str(key_out),
                         "-modulus", "-noout"]).strip()
    if not modulus_line.startswith("Modulus="):
        raise SystemExit(f"unexpected openssl modulus output: "
                         f"{modulus_line!r}")
    n_hex = modulus_line[len("Modulus="):].strip().lower()
    if len(n_hex) != 512:  # RSA-2048 -> 256 bytes -> 512 hex chars
        raise SystemExit(f"modulus is {len(n_hex) // 2} bytes, "
                         "expected 256 (RSA-2048)")
    module_out.parent.mkdir(parents=True, exist_ok=True)
    module_out.write_text(
        MODULE_TEMPLATE.format(n_hex=n_hex, e=EXPONENT),
        encoding="utf-8")
    return n_hex


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="make_update_key",
        description="Generate the BeeSky update-signing RSA keypair "
                    "(owner one-time setup; see docs/updating.md)")
    parser.add_argument("--key-out", default=str(DEFAULT_KEY_OUT),
                        help="where to write the PRIVATE key PEM "
                             f"(default {DEFAULT_KEY_OUT})")
    parser.add_argument("--module-out", default=str(DEFAULT_MODULE_OUT),
                        help="where to write the public-key module "
                             f"(default {DEFAULT_MODULE_OUT})")
    parser.add_argument("--force", action="store_true",
                        help="overwrite existing key/module files")
    args = parser.parse_args(argv)

    key_out = Path(args.key_out)
    module_out = Path(args.module_out)
    n_hex = generate(key_out, module_out, force=args.force)
    print(f"RSA-2048 keypair generated.")
    print(f"  private key : {key_out}  (modulus {n_hex[:16]}…)")
    print(f"  public half : {module_out} (UPDATE_RSA_N_HEX written)")
    print()
    print("NEXT STEPS (owner, one time):")
    print("  1. Store the PRIVATE key as a GitHub Actions secret:")
    print("       repo Settings -> Secrets and variables -> Actions ->")
    print("       New repository secret, name: UPDATE_SIGNING_KEY")
    print(f"       value: the ENTIRE contents of {key_out}")
    print("  2. Move the private key file somewhere safe (password")
    print("     manager / offline backup), then delete it from here.")
    print("     NEVER commit the private key.")
    print(f"  3. Commit the public half:  git add {module_out}")
    print("  4. Push a v* tag — the release workflow now signs")
    print("     update-manifest.json automatically (docs/updating.md).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
